from .ordering import ALLOWED_STATE
def finding_for_trigger(t,v):
 m={"REMAINING_RECORD":"REPORT_REMAINING_RECORD","EXPOSED_PII":"REPORT_EXPOSED_PII","ANONYMIZATION_INCOMPLETE":"REPORT_EXPOSED_PII","ACTIVE_DATA_FLOW":"REPORT_ACTIVE_DATA_FLOW","RESTORE_RISK":"REPORT_RESTORE_RISK"}
 op=m.get(t.trigger_kind); return (op,ALLOWED_STATE[op]) if op else (None,None)
def remediation_for_trigger(t,v):
 m={"REMAINING_RECORD":"DELETE_RECORD","EXPOSED_PII":"REDACT_RECORD","ANONYMIZATION_INCOMPLETE":"ANONYMIZE_RECORD","ACTIVE_DATA_FLOW":"DISABLE_DATA_FLOW","RESTORE_RISK":"BLOCK_RESTORE"}
 op=m.get(t.trigger_kind)
 if t.trigger_kind=="EXPOSED_PII" and v.required_action=="ANONYMIZE_RECORD":op="ANONYMIZE_RECORD"
 return (op,ALLOWED_STATE[op]) if op else (None,None)
def verification_for_trigger(t,v):
 m={"REMAINING_RECORD":"VERIFY_RECORD_ABSENT","EXPOSED_PII":"VERIFY_RECORD_REDACTED","ANONYMIZATION_INCOMPLETE":"VERIFY_RECORD_ANONYMIZED","ACTIVE_DATA_FLOW":"VERIFY_DATA_FLOW_DISABLED","RESTORE_RISK":"VERIFY_RESTORE_BLOCKED","RETENTION_VIOLATED":"VERIFY_RECORD_PRESENT"}; op=m[t.trigger_kind]; return op,ALLOWED_STATE[op]
def verification_for_compliant_verdict(action):
 m={"DELETE_RECORD":"VERIFY_RECORD_ABSENT","REDACT_RECORD":"VERIFY_RECORD_REDACTED","ANONYMIZE_RECORD":"VERIFY_RECORD_ANONYMIZED","RETAIN":"VERIFY_RECORD_PRESENT","DISABLE_DATA_FLOW":"VERIFY_DATA_FLOW_DISABLED","BLOCK_RESTORE":"VERIFY_RESTORE_BLOCKED"}
 op=m.get(action); return (op,ALLOWED_STATE[op]) if op else (None,None)
